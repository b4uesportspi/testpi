  async rebuildTournamentLeaderboard(tournamentId: string): Promise<TournamentLeaderboard[]> {
    if (!db) {
      throw new Error('Database not initialized');
    }

    await db.execute(sql`DELETE FROM tournament_leaderboards WHERE tournament_id = ${tournamentId}`);

    await db.execute(sql`
      WITH leaderboard_rows AS (
        SELECT
          mr.team_id AS team_id,
          RANK() OVER (
            ORDER BY SUM(mr.points_awarded) DESC,
                     SUM(mr.kills) DESC,
                     SUM(CASE WHEN mr.placement = 1 THEN 1 ELSE 0 END) DESC
          ) AS rank,
          SUM(mr.points_awarded) AS total_points,
          SUM(mr.kills) AS total_kills,
          COUNT(*) AS matches_played,
          SUM(CASE WHEN mr.wwcd > 0 THEN 1 ELSE 0 END) AS wwcd_count,
          SUM(CASE WHEN mr.placement = 1 THEN 1 ELSE 0 END) AS wins,
          SUM(COALESCE(mr.prize_pi, '0')) AS prize_sum
        FROM tournament_match_results mr
        JOIN tournament_matches m ON m.id = mr.match_id AND m.tournament_id = ${tournamentId}
        WHERE mr.team_id IS NOT NULL
        GROUP BY mr.team_id
      )
      INSERT INTO tournament_leaderboards (
        id, tournament_id, team_id, rank, total_points, total_kills, matches_played, wwcd_count, wins, prize_pi, prize_status, updated_at
      )
      SELECT
        gen_random_uuid(),
        ${tournamentId},
        lr.team_id,
        lr.rank,
        lr.total_points,
        lr.total_kills,
        lr.matches_played,
        lr.wwcd_count,
        lr.wins,
        COALESCE(lr.prize_sum, pd.prize_pi, '0'),
        CASE WHEN COALESCE(lr.prize_sum, pd.prize_pi, '0')::decimal > 0 THEN 'pending' ELSE 'not_awarded' END,
        now()
      FROM leaderboard_rows lr
      LEFT JOIN tournament_prize_distributions pd
        ON pd.tournament_id = ${tournamentId} AND pd.rank = lr.rank
      ORDER BY lr.rank;
    `);

    return this.getTournamentLeaderboard(tournamentId);
  }

