function isTransientDatabaseConnectionError(error: unknown): boolean {
  const message = error instanceof Error ? error.message : String(error);
  return /timeout exceeded|ECONN|ENOTFOUND|ETIMEDOUT|connection terminated|Connection terminated|database.*connect/i.test(message);
}

function delay(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function runWithConnectionRetry<T>(operationName: string, operation: () => Promise<T>): Promise<T> {
  let lastError: unknown;
  for (let attempt = 0; attempt < 2; attempt += 1) {
    try {
      return await operation();
    } catch (error: any) {
      const isPoolExhaustion = error?.code === 'EMAXCONNSESSION' || /max clients|pool_size|session mode/i.test(String(error?.message || error));
      lastError = error;
      if (!isPoolExhaustion || attempt === 1) {
        throw error;
      }

      console.warn(`Database pool exhausted while running ${operationName}; retrying once after a short delay...`, error?.message || error);
      await delay(750);
    }
  }

  throw lastError;
}

