  async rewardReferrer(referredUserId: string): Promise<void> {
    if (!db) {
      throw new Error('Database not initialized');
    }
    
    try {
      // First, get the referred user to find who referred them
      const [referredUser] = await db
        .select({
          referredBy: schema.users.referredBy
        })
        .from(schema.users)
        .where(eq(schema.users.id, referredUserId));
      
      if (!referredUser || !referredUser.referredBy) {
        console.log('No referrer found for user', referredUserId);
        return;
      }
      
      // Get the referrer user through the referral code
      const [referrer] = await db
        .select({
          userId: schema.referralCodes.userId
        })
        .from(schema.referralCodes)
        .where(eq(schema.referralCodes.code, referredUser.referredBy));
      
      if (!referrer) {
        console.log('Referrer not found with code', referredUser.referredBy);
        return;
      }

      // Prevent duplicate referral reward processing
      const [existingReward] = await db
        .select({ id: schema.referralRewards.id })
        .from(schema.referralRewards)
        .where(eq(schema.referralRewards.referredUserId, referredUserId));

      if (existingReward) {
        console.log('Referral reward already processed for referred user', referredUserId);
        return;
      }

      const referralRewardTokens = 25;

      // Record the referral reward for analytics and auditing
      await db.insert(schema.referralRewards).values({
        id: randomUUID(),
        referrerId: referrer.userId,
        referredUserId,
        tokensAwarded: referralRewardTokens,
        rewardStatus: 'awarded',
        createdAt: new Date(),
        awardedAt: new Date(),
      });

      // Add B4U Esports Token rewards to both users and keep the ledger in sync.
      await db.update(schema.users)
        .set({ 
          tokens: sql`${schema.users.tokens} + ${referralRewardTokens}`,
          updatedAt: new Date() 
        })
        .where(eq(schema.users.id, referrer.userId));
      await db.insert(schema.tokenTransactions).values({
        userId: referrer.userId,
        amount: referralRewardTokens,
        type: 'referral_reward',
        description: `Referral reward: ${referralRewardTokens} B4U Esports Token`,
        referenceId: referredUserId,
      });

      await db.update(schema.users)
        .set({ 
          tokens: sql`${schema.users.tokens} + ${referralRewardTokens}`,
          updatedAt: new Date() 
        })
        .where(eq(schema.users.id, referredUserId));
      await db.insert(schema.tokenTransactions).values({
        userId: referredUserId,
        amount: referralRewardTokens,
        type: 'referral_reward',
        description: `Referral signup reward: ${referralRewardTokens} B4U Esports Token`,
        referenceId: referrer.userId,
      });

      console.log(`Added ${referralRewardTokens} referral tokens to referrer ${referrer.userId} and referred user ${referredUserId}`);
    } catch (error) {
      console.error('Error rewarding referrer:', error);
      throw error;
    }
  }
  
